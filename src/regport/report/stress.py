"""``reports/stress.md``, ``reports/tables/stress.csv`` and ``figures/stress_<window>.png``."""

from __future__ import annotations

from datetime import date, timedelta
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import polars as pl

from regport.config import ExperimentConfig
from regport.eval.evaluate import Run
from regport.eval.stress import drawdown_stats
from regport.report.tables import md_table, write_csv


def stress_table(runs: list[Run], windows: dict[str, tuple[date, date]]) -> pl.DataFrame:
    rows = []
    for name, (start, end) in windows.items():
        for run in runs:
            dates = run.returns["date"].to_list()
            st = drawdown_stats(run.returns["ret"].to_numpy(), dates, start, end)
            rows.append(
                {
                    "window": name,
                    "strategy": "1/N" if run.optimizer == "equal_weight" else run.label,
                    "window_return": st.window_return,
                    "max_drawdown": st.max_drawdown,
                    "peak": str(st.peak_date),
                    "trough": str(st.trough_date),
                    "days_to_trough": st.days_to_trough,
                    "recovery": st.recovery_text,
                    "worst_5d_return": st.worst_5d_return,
                    "realized_vol": st.realized_vol,
                }
            )
    return pl.DataFrame(rows)


def stress_figure(
    runs: list[Run],
    labels: list[str],
    name: str,
    window: tuple[date, date],
    stress_prob: pl.DataFrame | None,
    cp_prob: pl.DataFrame | None,
    path: Path,
    pad: int = 60,
) -> Path:
    start, end = window
    lo, hi = start - timedelta(days=pad), end + timedelta(days=pad)
    fig, (top, bottom) = plt.subplots(
        2, 1, figsize=(9, 5.4), sharex=True, gridspec_kw={"height_ratios": [2, 1]}
    )
    for run in runs:
        label = "1/N" if run.optimizer == "equal_weight" else run.label
        if label not in labels:
            continue
        r = run.returns.filter(pl.col("date").is_between(lo, hi))
        wealth = np.cumprod(1 + r["ret"].to_numpy())
        top.plot(
            np.array(r["date"].to_list(), dtype="datetime64[D]"),
            wealth / wealth[0],
            label=label,
            lw=1.1,
        )
    top.axvspan(np.datetime64(start, "D"), np.datetime64(end, "D"), color="0.9", zorder=0)
    top.set_ylabel("growth of 1")
    top.legend(fontsize=8)
    top.set_title(name.replace("_", " "))
    for frame, col, label in (
        (stress_prob, "p_stress", "HMM P(high-vol states)"),
        (cp_prob, "cp_prob_short", "BOCPD P(run < 21)"),
    ):
        if frame is not None:
            f = frame.filter(pl.col("date").is_between(lo, hi))
            bottom.plot(
                np.array(f["date"].to_list(), dtype="datetime64[D]"), f[col], lw=0.9, label=label
            )
    bottom.set_ylim(-0.02, 1.02)
    bottom.legend(fontsize=8)
    bottom.tick_params(axis="x", labelrotation=30, labelsize=8)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120, metadata={"Software": None})
    plt.close(fig)
    return path


def write_stress(
    runs: list[Run],
    cfg: ExperimentConfig,
    headline: str,
    stress_prob: pl.DataFrame | None,
    cp_prob: pl.DataFrame | None,
    reports_dir: Path,
) -> dict[str, Path]:
    windows = cfg.evaluation.stress_windows
    table = stress_table(runs, windows)
    out: dict[str, Path] = {"csv": write_csv(table, reports_dir / "tables" / "stress.csv")}
    labels = [headline, headline.split("+")[0], "1/N"]
    lines = [
        "# Stress tests",
        "",
        "Generated by `regport stress`; do not edit by hand.",
        "",
        "Windows are fixed in the config and were never tuned. Drawdowns are measured "
        "against the high-water mark entering each window; recovery counts trading days "
        "from the trough until the peak level is regained.",
        "",
    ]
    for name, window in windows.items():
        part = table.filter(pl.col("window") == name).sort("max_drawdown", descending=True)
        lines += [
            f"## {name.replace('_', ' ')} ({window[0]} to {window[1]})",
            "",
            *md_table(part.drop("window")),
            "",
            f"![{name}](figures/stress_{name}.png)",
            "",
        ]
        out[name] = stress_figure(
            runs,
            labels,
            name,
            window,
            stress_prob,
            cp_prob,
            reports_dir / "figures" / f"stress_{name}.png",
        )
    md = reports_dir / "stress.md"
    md.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    out["md"] = md
    return out
