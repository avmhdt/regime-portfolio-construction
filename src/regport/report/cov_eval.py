"""``reports/cov_eval.md`` and ``reports/tables/cov_eval.csv`` (FR-10, AC-W-03)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import polars as pl

from regport.report.figures import cov_eval_bias
from regport.report.tables import md_table, write_csv
from regport.risk.evaluation import CovEvalResult, ac_w_03, select_estimator

SAMPLE_LABELS = {
    "selection": "selection half (windows ending by {sel})",
    "second_half": "second half (origins after {sel})",
    "full": "full OOS",
}


def origin_frame(result: CovEvalResult) -> pl.DataFrame:
    """Per-origin detail for ``results/cov_eval/`` (git-ignored)."""
    frames = []
    for (name, h), s in result.scores.items():
        if not s.origin:
            continue
        ret, fvar, rv = s.arrays()
        frames.append(
            pl.DataFrame(
                {
                    "estimator": name,
                    "horizon_days": h,
                    "origin": s.origin,
                    "end": s.end,
                    "n_assets": s.n_assets,
                    "ret_equal_weight": ret[:, 0],
                    "fvol_equal_weight": np.sqrt(fvar[:, 0]),
                    "ret_min_variance": ret[:, 1],
                    "fvol_min_variance": np.sqrt(fvar[:, 1]),
                    "rv_equal_weight": rv[:, 0],
                }
            )
        )
    return pl.concat(frames).sort("estimator", "horizon_days", "origin")


def write_cov_eval(
    result: CovEvalResult, table: pl.DataFrame, reports_dir: Path, results_dir: Path
) -> dict[str, Path]:
    chosen = select_estimator(table)
    passed, b_1n, b_rand = ac_w_03(table, chosen)
    csv = write_csv(table, reports_dir / "tables" / "cov_eval.csv")
    fig = cov_eval_bias(table, reports_dir / "figures" / "cov_eval_bias.png")
    detail = results_dir / "cov_eval" / "origins.parquet"
    detail.parent.mkdir(parents=True, exist_ok=True)
    origin_frame(result).write_parquet(detail)

    sel = result.selection_end.isoformat()
    lines = [
        "# Covariance estimators: out-of-sample risk forecasts",
        "",
        "Generated by `regport cov-eval`; do not edit by hand.",
        "",
        f"- OOS period: {result.oos_start} to {result.oos_end}. Non-overlapping windows of "
        f"{', '.join(map(str, result.horizons))} trading days.",
        "- Portfolios scored at each origin: 1/N, 100 random long-only Dirichlet(1) portfolios "
        "(the same for every estimator), and each estimator's own capped minimum-variance "
        "portfolio.",
        f"- Asset exclusions under DQ-04 (more than 5% null returns in the 504-day window): "
        f"{result.excluded_events} asset-origins. Min-variance solver failures: "
        f"{result.solver_failures}.",
        "",
        "## Selection (D-12)",
        "",
        "The rule fixed in `docs/decisions.md` before this evaluation: lowest mean QLIKE at "
        f"h = 21 "
        f"over 1/N and the random portfolios, on windows ending by {sel}.",
        "",
    ]
    choice = table.filter((pl.col("sample") == "selection") & (pl.col("horizon_days") == 21))
    lines += md_table(
        choice.sort("qlike_mean"),
        [
            "estimator",
            "n_windows",
            "qlike_mean",
            "b_equal_weight",
            "b_random_median",
            "min_variance_realized_vol",
        ],
        digits=4,
    )
    lines += [
        "",
        f"**Chosen estimator: `{chosen}`.**",
        "",
        "## AC-W-03",
        "",
        f"For `{chosen}` at h = 21 over the full OOS: b = {b_1n:.3f} for 1/N and "
        f"{b_rand:.3f} for the median random portfolio. The criterion is [0.90, 1.10] for both: "
        f"**{'pass' if passed else 'FAIL'}**.",
    ]
    for sample in ("full", "second_half", "selection"):
        for h in result.horizons:
            part = table.filter((pl.col("sample") == sample) & (pl.col("horizon_days") == h))
            if part.is_empty():
                continue
            lines += ["", f"## h = {h} days, {SAMPLE_LABELS[sample].format(sel=sel)}", ""]
            lines += md_table(
                part,
                [
                    "estimator",
                    "n_windows",
                    "b_equal_weight",
                    "b_random_median",
                    "b_random_p05",
                    "b_random_p95",
                    "b_min_variance",
                    "band_lo95",
                    "band_hi95",
                    "qlike_mean",
                    "min_variance_realized_vol",
                    "min_variance_forecast_vol",
                ],
            )
    lines += ["", "![Bias statistic by estimator and horizon](figures/cov_eval_bias.png)", ""]
    md = reports_dir / "cov_eval.md"
    md.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    return {"report": md, "table": csv, "figure": fig, "detail": detail}
