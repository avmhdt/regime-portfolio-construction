"""``reports/scaling.md``, ``reports/tables/scaling.csv`` and ``figures/scaling_runtime.png``."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import polars as pl

from regport.report.tables import md_table, write_csv

HARDWARE = (
    "Intel Core i9-14900K (24 cores, 32 threads), 128 GB RAM, Windows 11 Pro, Python 3.12; "
    "BLAS threads limited to 1 while live recorders run on the same PC (P-10)"
)


def runtime_figure(table: pl.DataFrame, path: Path) -> Path:
    fig, ax = plt.subplots(figsize=(8, 4.2))
    synth = table.filter(pl.col("universe").str.contains(r"^\d+$"))
    for method in synth["method"].unique(maintain_order=True).to_list():
        part = synth.filter(pl.col("method") == method).sort("n_assets")
        ax.plot(part["n_assets"], part["median_seconds"], marker="o", lw=1, label=method)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("assets (N)")
    ax.set_ylabel("median seconds per call")
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120, metadata={"Software": None})
    plt.close(fig)
    return path


def write_scaling(
    table: pl.DataFrame, cond: pl.DataFrame, hrp_vs_mv: pl.DataFrame | None, reports_dir: Path
) -> dict[str, Path]:
    out = {
        "csv": write_csv(table, reports_dir / "tables" / "scaling.csv"),
        "cond_csv": write_csv(cond, reports_dir / "tables" / "scaling_condition.csv"),
        "figure": runtime_figure(table, reports_dir / "figures" / "scaling_runtime.png"),
    }
    lines = [
        "# Scaling to 500 assets",
        "",
        "Generated by `regport bench scaling`; do not edit by hand. Timings are wall-clock "
        "medians on one machine and vary from run to run, so they are reported, not frozen.",
        "",
        f"- Hardware: {HARDWARE}.",
        "- Data: synthetic 5-factor daily returns, 504-day window; plus the Kenneth French 49 "
        "industries where noted.",
        "",
        "## Runtime and memory per call",
        "",
        *md_table(
            table.sort("stage", "method", "n_assets"),
            ["universe", "stage", "method", "median_seconds", "peak_mib"],
            digits=4,
        ),
        "",
        "## Conditioning (N/T)",
        "",
        *md_table(cond.sort("estimator", "n_assets"), digits=1),
        "",
    ]
    if hrp_vs_mv is not None:
        lines += [
            "## HRP vs min-variance out of sample, 49 industries",
            "",
            "From the Kenneth French robustness runs (`reports/robustness.md`).",
            "",
            *md_table(hrp_vs_mv, digits=4),
            "",
        ]
    lines += ["![Runtime](figures/scaling_runtime.png)"]
    md = reports_dir / "scaling.md"
    md.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    out["md"] = md
    return out
