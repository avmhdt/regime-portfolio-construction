"""``reports/robustness.md`` and ``reports/tables/robustness_*.csv``."""

from __future__ import annotations

from pathlib import Path

import polars as pl

from regport.report.tables import md_table, write_csv

COLS = [
    "optimizer",
    "regime",
    "sharpe",
    "delta_sharpe_vs_1n",
    "p_hac",
    "ceq",
    "annual_volatility",
    "annual_turnover",
    "max_drawdown",
]


def write_robustness(
    tables: dict[str, pl.DataFrame],
    break_even: pl.DataFrame | None,
    alfred_regime: dict[str, float] | None,
    notes: dict[str, str],
    reports_dir: Path,
) -> dict[str, Path]:
    out: dict[str, Path] = {}
    lines = [
        "# Robustness",
        "",
        "Generated by `regport robustness`; do not edit by hand.",
        "",
        "Each suite's p-values are the Ledoit-Wolf (2008) HAC test of the net Sharpe "
        "difference against the 1/N run of the same variant. Every run is a row in the "
        "trial log.",
        "",
    ]
    titles = {
        "costs": "Uniform cost grid",
        "common_start": "Common-start panel (D-02 a)",
        "french": "Kenneth French industries",
        "alfred": "ALFRED vintage vs revised",
    }
    for suite, table in tables.items():
        table = table.drop([c for c in ("run_id",) if c in table.columns])
        out[suite] = write_csv(table, reports_dir / "tables" / f"robustness_{suite}.csv")
        lines += [f"## {titles.get(suite, suite)}", ""]
        if suite in notes:
            lines += [notes[suite], ""]
        for variant in table["variant"].unique(maintain_order=True).to_list():
            part = table.filter(pl.col("variant") == variant).sort("sharpe", descending=True)
            lines += [f"### {variant}", "", *md_table(part, COLS), ""]
        if suite == "costs" and break_even is not None:
            lines += ["### Break-even cost against 1/N", "", *md_table(break_even), ""]
        if suite == "alfred" and alfred_regime is not None:
            write_csv(
                pl.DataFrame(
                    {"metric": list(alfred_regime), "value": list(alfred_regime.values())}
                ),
                reports_dir / "tables" / "robustness_alfred_regime.csv",
            )
            lines += [
                "Regime probabilities, point-in-time vs latest-revised macro features. The two "
                "runs are labelled independently, so the comparison is label-invariant:",
                "",
                "- Mean absolute difference in the stress probability (high-volatility states): "
                f"{alfred_regime['stress_probability_mad']:.4f}.",
                "- Mean absolute difference per state after Hungarian matching of the last fits: "
                f"{alfred_regime['aligned_state_probability_mad']:.4f}.",
                "- Days on which the most likely state agrees: "
                f"{100 * alfred_regime['argmax_agreement']:.1f}%.",
                "",
            ]
    md = reports_dir / "robustness.md"
    md.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    out["md"] = md
    return out
